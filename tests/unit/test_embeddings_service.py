# ── Memory write with embedding tests ─────────────────────────────────────


class TestMemoryWriteEmbeds:
    """MemoryService.write generates embeddings for new records."""

    @pytest.mark.asyncio
    async def test_write_generates_embedding_with_session(self):
        """_persist_record calls generate_embedding when content is present and session given."""
        service = MemoryService()
        record = MemoryRecord(
            memory_id="test-emb-1",
            memory_type="SEMANTIC",
            scope="USER",
            tenant_id="tenant-1",
            workspace_id="ws-1",
            user_id="user-1",
            content="Test memory content for embedding",
            authority={"score": 0.8},
        )
        # Test the embedding is generated by calling _persist_record directly
        # via a mock session — verify generate_embedding is called
        with patch("app.services.embeddings.generate_embedding") as mock_emb:
            mock_emb.return_value = ([0.1] * 384, "test-model", 384)
            mock_session = MagicMock()
            # Make flush a coroutine
            async def mock_flush():
                pass
            mock_session.flush = mock_flush
            # Also mock the select query inside _load_from_db
            with patch.object(service, "_load_from_db", return_value=None):
                await service._persist_record(mock_session, record)
            mock_emb.assert_called_once()
            call_args = mock_emb.call_args[0][0]
            assert "Test memory content" in call_args
            # Verify the model was created with embedding fields
            added = mock_session.add.call_args[0][0]
            assert added.embedding is not None
            assert added.embedding_model == "test-model"
            assert added.embedding_dimension == 384

    @pytest.mark.asyncio
    async def test_write_empty_content_no_embedding(self):
        """Empty content doesn't crash the write path."""
        service = MemoryService()
        record = MemoryRecord(
            memory_id="test-emb-empty",
            memory_type="SEMANTIC",
            scope="USER",
            tenant_id="tenant-1",
            workspace_id="ws-1",
            user_id="user-1",
            content="",
            authority={"score": 0.8},
        )
        result = await service.write(
            record,
            principal_id="user-1",
            session=None,
        )
        assert result is not None


