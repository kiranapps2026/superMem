# ── Crash recovery test ───────────────────────────────────────────────────


class TestCrashRecovery:
    """Crash recovery: killing and restarting backfill doesn't duplicate work."""

    @pytest.mark.asyncio
    async def test_content_hash_prevents_duplicates(self):
        """Content hash + version check prevents duplicate embeddings."""
        text = "recovery test content"
        chash = content_hash(text)
        target_ver = embedding_version()
        # The backfill uses content_hash + embedding_version as the idempotency key
        # If a row has both set, it's skipped
        assert chash == content_hash(text)  # deterministic
        assert target_ver == embedding_version()  # deterministic per config
