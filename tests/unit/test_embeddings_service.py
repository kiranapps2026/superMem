class TestEmbeddingGeneration:
    """Unit tests for embedding generation."""

    def test_generate_embedding_returns_list_and_metadata(self):
        embedding, model_name, dim = generate_embedding("test content")
        assert isinstance(embedding, list)
        assert len(embedding) > 0
        assert model_name != ""
        assert dim > 0
        assert all(isinstance(x, float) for x in embedding)

    def test_generate_embedding_dimension(self):
        _, _, dim = generate_embedding("hello world")
        assert dim > 0

    def test_different_texts_produce_different_embeddings(self):
        emb1, _, _ = generate_embedding("apple banana cherry")
        emb2, _, _ = generate_embedding("dog cat mouse")
        assert emb1 != emb2

    def test_same_text_produces_same_embedding(self):
        emb1, _, _ = generate_embedding("same text here")
        emb2, _, _ = generate_embedding("same text here")
        assert emb1 == emb2

    def test_embedding_version_returns_string(self):
        ver = embedding_version()
        assert isinstance(ver, str)
        assert ":" in ver

    def test_content_hash_is_deterministic(self):
        h1 = content_hash("hello world")
        h2 = content_hash("hello world")
        assert h1 == h2
        assert len(h1) == 64  # SHA-256 hex

    def test_content_hash_different_texts(self):
        h1 = content_hash("hello")
        h2 = content_hash("world")
        assert h1 != h2

    def test_fit_corpus_then_embed(self):
        texts = [
            "The cat sat on the mat",
            "A dog ran through the park",
            "The cat chased the mouse",
            "Birds fly in the sky",
            "The dog barked loudly",
        ]
        fit_corpus(texts)
        model = get_model()
        assert model._fitted is True
        emb = generate_embedding("The cat sat")
        assert isinstance(emb[0], list)
        assert len(emb[0]) > 0


class TestHashFallbackEmbedding:
    """Tests for the deterministic fallback embedding."""

    def test_hash_embed_produces_normalized_vector(self):
        model = _EmbeddingModel()
        vec = model._hash_embed("test text", dim=128)
        assert len(vec) == 128
        norm = np.linalg.norm(np.array(vec))
        assert abs(norm - 1.0) < 0.01


